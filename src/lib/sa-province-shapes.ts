export const MAP_BOUNDS = { west: 16.2, east: 33.2, north: -22.0, south: -35.0 };

export function project(lng: number, lat: number, width = 720, height = 560): { x: number; y: number } {
  const x = ((lng - MAP_BOUNDS.west) / (MAP_BOUNDS.east - MAP_BOUNDS.west)) * width;
  const y = ((MAP_BOUNDS.north - lat) / (MAP_BOUNDS.north - MAP_BOUNDS.south)) * height;
  return { x, y };
}

export function ringToPath(ring: [number, number][], width = 720, height = 560): string {
  return ring
    .map((pt, i) => {
      const { x, y } = project(pt[0], pt[1], width, height);
      return `${i === 0 ? 'M' : 'L'}${x.toFixed(1)},${y.toFixed(1)}`;
    })
    .join(' ') + ' Z';
}
